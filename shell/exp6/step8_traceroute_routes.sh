#   1. 三条 traceroute 输出（-n 不解析域名）:
#      -> 192.168.57.126: 192.168.56.1(RB) 192.168.56.246(RA)
#                         192.168.56.249(RC) 192.168.57.126(H57A)
#      -> 192.168.57.190: ...RB RA RC RE 192.168.57.190（4 跳路由器）
#      -> 192.168.57.254: ...RB RA RD 192.168.57.254（3 跳路由器）
#      每行一个途经节点，最后一行为目标主机；
#   2. 途经路由器的路由表打印出来，可对照验证每跳的转发决策
#      （最长前缀匹配）；
#   3. 若某跳显示 * * *，多为该路由器对 traceroute 探测包限速回复，
#      不影响后续跳显示，属正常现象。

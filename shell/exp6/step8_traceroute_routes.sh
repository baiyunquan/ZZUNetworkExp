#!/usr/bin/env bash
# =============================================================
# 实验6 步骤8：跟踪路由 + 分析途经路由器路由表（理解 IP 转发算法）
# 对应指导书《实验6》步骤8 (1)-(6)
# 用法: sudo ./step8_traceroute_routes.sh
# =============================================================
set -euo pipefail
NS_H56A="H56A"

[ "$(id -u)" -eq 0 ] || { echo "[错误] 请使用 sudo 执行" >&2; exit 1; }
ip netns list | grep -q "$NS_H56A" || { echo "[错误] 拓扑未创建，先运行 create_topology.sh create" >&2; exit 1; }

# 目标主机 -> 预期途经路由器（按拓扑规划）
declare -A TARGETS=(
    ["192.168.57.126"]="H57A|RB RA RC"
    ["192.168.57.190"]="H57B|RB RA RC RE"
    ["192.168.57.254"]="H57C|RB RA RD"
)

for dst in 192.168.57.126 192.168.57.190 192.168.57.254; do
    meta="${TARGETS[$dst]}"
    host="${meta%%|*}"; routers="${meta#*|}"
    echo "=========================================================="
    echo "==> traceroute -n $dst （目标: $host）"
    echo "----------------------------------------------------------"
    ip netns exec "$NS_H56A" traceroute -n -w 2 -q 1 -m 8 "$dst" 2>/dev/null || true

    echo ""
    echo "==> 途经路由器路由表（等价指导书 ip route / routel）"
    for r in $routers; do
        echo "--- 路由器 $r 的路由表 (ip route) ---"
        ip netns exec "$r" ip route
        echo "--- 路由器 $r 的路由表 (routel 格式) ---"
        ip netns exec "$r" routel 2>/dev/null | head -8 || ip netns exec "$r" ip route | head -8
        echo ""
    done
done

echo "=========================================================="
echo "==> IP 分组转发算法解读"
cat <<'EOF'
   路由器转发流程（逐跳）:
     1. 收到 IP 分组，提取目的 IP；
     2. 查路由表: 按"最长前缀匹配"选择路由条目
        （直连路由 > 静态路由 > 默认路由 0.0.0.0/0）；
     3. 命中 -> TTL 减 1、重算首部校验和、改写二层头，从出接口转发；
        未命中且无默认路由 -> 丢弃并回 ICMP Destination Unreachable；
     4. 目的地址是本机地址 -> 交付本机上层协议。
   本实验三条路径验证:
     H56A->H57A: RB -> RA -> RC -> H57A（RA 查 57.0/25 经 RC）
     H56A->H57B: RB -> RA -> RC -> RE -> H57B（RC 查 57.128/26 经 RE）
     H56A->H57C: RB -> RA -> RD -> H57C（RA 查 57.192/26 经 RD）
   每一跳的转发决策完全由该路由器自己的路由表决定 —— 这就是
   逐跳寻址（hop-by-hop）的 IP 分组转发算法。
EOF

# ------------------------------------------------------------
